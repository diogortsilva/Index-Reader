"""Regenerate index_reader/sample_headers.py from a reference workbook.

Usage: python tools/make_sample_headers.py REFERENCE.xlsx
"""
import sys
import warnings
import os

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import openpyxl
from openpyxl.utils import get_column_letter


def norm(v):
    if v is None:
        return ""
    return " ".join(str(v).upper().split())


def main(path):
    warnings.simplefilter("ignore")
    wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
    ws = wb["LOOP"]
    rows = list(ws.iter_rows(min_row=1, max_row=2, values_only=True))
    out = ['"""Header text of every column in the reference Instrument Index (sheet LOOP).',
           "",
           "Generated by tools/make_sample_headers.py - do not edit by hand.",
           "Each entry: (column letter, row-1 short code, row-2 description), normalized",
           "to upper case with all whitespace collapsed to single spaces.",
           '"""',
           "",
           "SAMPLE_HEADERS = ["]
    n = max(len(rows[0]), len(rows[1]))
    for i in range(n):
        a = norm(rows[0][i]) if i < len(rows[0]) else ""
        b = norm(rows[1][i]) if i < len(rows[1]) else ""
        if not a and not b:
            continue
        out.append("    (%r, %r, %r)," % (get_column_letter(i + 1), a, b))
    out.append("]")
    out.append("")
    target = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                          "index_reader", "sample_headers.py")
    with open(target, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print("wrote", target, n, "columns")


if __name__ == "__main__":
    main(sys.argv[1])
